/**
 * Generates backend/apps-script/Destinations.gs — the compact destination registry used by the Apps Script
 * backend for id validation, the Results tab and ranking eligibility.
 *
 *   npm run backend:registry
 *
 * For every id D01–D20:
 *   - a valid data/destinations/DXX-*.json → name, title, version, security status, realistic total
 *     (src/lib/budget.ts, flights included), budget status, material uncertainty;
 *   - missing or invalid file → the id with its name from AGENTS.md and `pending: true` (never ranking-eligible).
 * Output is deterministic (no timestamps) so regenerating without data changes produces no diff.
 * After regenerating, paste the new Destinations.gs into the Apps Script project and redeploy.
 */
import { readFileSync, readdirSync, writeFileSync, existsSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
import { Destination, DESTINATION_IDS } from '../src/types/destination';
import { headlineTotals, hasMaterialUncertainty } from '../src/lib/budget';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const destDir = join(root, 'data/destinations');
const outFile = join(root, 'backend/apps-script/Destinations.gs');

/** Fallback names (AGENTS.md §2 table). The table in AGENTS.md wins when it can be parsed. */
const FALLBACK_NAMES: Record<string, string> = {
  D01: 'Taiwan', D02: 'Iraq', D03: 'China — Yunnan', D04: 'India — Northeast', D05: 'Algeria',
  D06: 'Saudi Arabia', D07: 'Jordan', D08: 'Tunisia', D09: 'Egypt', D10: 'Sri Lanka', D11: 'Laos',
  D12: 'Vietnam', D13: 'Philippines', D14: 'Japan — Kyushu', D15: 'Ethiopia', D16: 'Senegal',
  D17: 'South Africa', D18: 'Guatemala', D19: 'Mexico — Oaxaca & Chiapas', D20: 'Chile — Atacama',
};

function namesFromAgentsMd(): Record<string, string> {
  const names = { ...FALLBACK_NAMES };
  const path = join(root, 'AGENTS.md');
  if (!existsSync(path)) return names;
  for (const line of readFileSync(path, 'utf8').split('\n')) {
    const m = /^\|\s*(D\d{2})\s*\|\s*([^|]+?)\s*\|/.exec(line);
    if (m) names[m[1]] = m[2];
  }
  return names;
}

interface RegistryEntry {
  name: string;
  title: string | null;
  version: string | null;
  securityStatus: 'eligible' | 'conditional' | 'excluded' | null;
  realisticTotalEUR: number | null;
  budgetStatus: string | null;
  materialUncertainty: boolean | null;
  pending: boolean;
}

const names = namesFromAgentsMd();
const files = existsSync(destDir) ? readdirSync(destDir).filter((f) => /^D\d{2}-.*\.json$/.test(f)).sort() : [];
const registry: Record<string, RegistryEntry> = {};
const notes: string[] = [];

// The original 20 (pending until researched) plus any later additions found on disk (D21, D22, …).
const ids = [...new Set<string>([...DESTINATION_IDS, ...files.map((f) => f.slice(0, 3))])].sort();
for (const id of ids) {
  const pending: RegistryEntry = {
    name: names[id] ?? id, title: null, version: null, securityStatus: null,
    realisticTotalEUR: null, budgetStatus: null, materialUncertainty: null, pending: true,
  };
  const matches = files.filter((f) => f.startsWith(`${id}-`));
  if (matches.length === 0) {
    registry[id] = pending;
    notes.push(`${id} pending (no data file yet)`);
    continue;
  }
  if (matches.length > 1) notes.push(`${id}: several files (${matches.join(', ')}); using ${matches[0]}`);
  let raw: unknown;
  try {
    raw = JSON.parse(readFileSync(join(destDir, matches[0]), 'utf8'));
  } catch (e) {
    registry[id] = pending;
    notes.push(`${id} pending (invalid JSON: ${(e as Error).message})`);
    continue;
  }
  const parsed = Destination.safeParse(raw);
  if (!parsed.success) {
    registry[id] = pending;
    notes.push(`${id} pending (fails the schema: ${parsed.error.issues.length} issue(s); run npm run validate -- ${id})`);
    continue;
  }
  const d = parsed.data;
  if (d.id !== id) {
    registry[id] = pending;
    notes.push(`${id} pending (file declares id ${d.id})`);
    continue;
  }
  const totals = headlineTotals(d.budget);
  registry[id] = {
    name: names[id] ?? d.country,
    title: d.title,
    version: d.version,
    securityStatus: d.security.status,
    realisticTotalEUR: Math.round(totals.totalPerPerson * 100) / 100,
    budgetStatus: totals.status,
    materialUncertainty: hasMaterialUncertainty(d.budget),
    pending: false,
  };
}

const body = ids.map((id) => `  ${JSON.stringify(id)}: ${JSON.stringify(registry[id])},`).join('\n');
const out = `/**
 * Destinations.gs — GENERATED by scripts/build-backend-registry.ts. Do not edit by hand.
 * Regenerate with \`npm run backend:registry\`, then paste this file into the Apps Script project and redeploy.
 *
 * One entry per destination id. \`pending: true\` = research not yet available or not valid: the id is accepted for
 * evaluations but the destination is never ranking-eligible. realisticTotalEUR is per person, flights included
 * (realistic scenario, src/lib/budget.ts). budgetStatus uses the thresholds in AGENTS.md §5.
 */
var DESTINATION_REGISTRY = {
${body}
};
`;

writeFileSync(outFile, out);
const ready = ids.filter((id) => !registry[id].pending).length;
console.log(`Wrote ${outFile.replace(root + '/', '')}: ${ready} destination(s) with data, ${ids.length - ready} pending.`);
for (const n of notes) console.log(`  · ${n}`);
