/**
 * Generate the image attribution register (docs/image-credits/README.md) and the source
 * register (docs/research/source-register.md) from the data files.  `npm run credits`
 */
import { readFileSync, readdirSync, writeFileSync, mkdirSync, existsSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
import { Destination, ImageCreditFile } from '../src/types/destination';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const destDir = join(root, 'data/destinations');
const esc = (s: string) => s.replace(/\|/g, '\\|').replace(/\n/g, ' ');

const files = readdirSync(destDir).filter((f) => /^D\d{2}-.*\.json$/.test(f)).sort();
let images = '# Image attribution register\n\nGenerated by `npm run credits` from `data/images/*.json`. Licence and author data come from the Wikimedia Commons API (`npm run images`), never typed by hand. Only public-domain, CC0, CC BY and CC BY-SA files are accepted.\n\n';
let sources = '# Source register\n\nGenerated by `npm run credits` from the `sources` of every destination file. Planning estimates are labelled as such in the data (`confidence`).\n\n';
let imageCount = 0;
let sourceCount = 0;
for (const f of files) {
  const d = Destination.parse(JSON.parse(readFileSync(join(destDir, f), 'utf8')));
  const creditPath = join(root, 'data/images', `${d.id}.json`);
  const credits = existsSync(creditPath) ? ImageCreditFile.parse(JSON.parse(readFileSync(creditPath, 'utf8'))) : [];
  images += `## ${d.id} — ${d.country}\n\n| Id | Location | Author | Licence | Source |\n|---|---|---|---|---|\n`;
  for (const c of credits) {
    images += `| ${c.id} | ${esc(c.location)} | ${esc(c.photographer)} | ${c.licenceUrl ? `[${c.licence}](${c.licenceUrl})` : c.licence} | [${esc(c.commonsFile)}](${c.sourceUrl}) |\n`;
    imageCount++;
  }
  images += '\n';
  sources += `## ${d.id} — ${d.country}\n\n| Id | Title | Publisher | Type | Accessed | Supports |\n|---|---|---|---|---|---|\n`;
  for (const s of d.sources) {
    sources += `| ${s.id} | [${esc(s.title)}](${s.url}) | ${esc(s.publisher)} | ${s.type} | ${s.accessedAt} | ${esc(s.claims.join('; '))} |\n`;
    sourceCount++;
  }
  sources += '\n';
}
images = images.replace('\n\n', `\n\n**${imageCount} photographs across ${files.length} destinations.**\n\n`);
sources = sources.replace('\n\n', `\n\n**${sourceCount} sources across ${files.length} destinations.**\n\n`);
mkdirSync(join(root, 'docs/image-credits'), { recursive: true });
writeFileSync(join(root, 'docs/image-credits/README.md'), images);
writeFileSync(join(root, 'docs/research/source-register.md'), sources);
console.log(`image register: ${imageCount} images · source register: ${sourceCount} sources`);
